class DataContractError(ValueError):
    """Raised when the input file cannot be analysed safely."""


def log(message: str = "") -> None:
    print(message)
    LOG.append(message)


def validate_input_schema(frame: pd.DataFrame) -> None:
    """Fail before parsing if a required column is absent or the file is empty."""
    if frame.empty:
        raise DataContractError("input file has no data rows")
    missing = [column for column in REQUIRED_COLUMNS if column not in frame.columns]
    if missing:
        raise DataContractError("input is missing required column(s): " + ", ".join(missing))
    blank_ids = frame.application_id.isna() | frame.application_id.eq("")
    if blank_ids.any():
        raise DataContractError(f"application_id is blank in {int(blank_ids.sum())} row(s)")


def wilson_ci(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% Wilson score interval for a proportion, returned in percent."""
    if n == 0:
        return (np.nan, np.nan)
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return (max(0.0, 100 * (centre - half)), min(100.0, 100 * (centre + half)))


def add_wilson(df: pd.DataFrame, k_col: str, n_col: str) -> pd.DataFrame:
    df = df.copy()
    intervals = [wilson_ci(int(k), int(n)) for k, n in zip(df[k_col], df[n_col], strict=True)]
    df["ci_low"], df["ci_high"] = zip(*intervals, strict=True)
    return df


def newcombe_diff(k1: int, n1: int, k2: int, n2: int) -> tuple[float, float]:
    """Newcombe hybrid score interval for p1 - p2, returned in proportion units."""
    p1, p2 = k1 / n1, k2 / n2
    low1, high1 = (value / 100 for value in wilson_ci(k1, n1))
    low2, high2 = (value / 100 for value in wilson_ci(k2, n2))
    diff = p1 - p2
    lower = diff - np.sqrt((p1 - low1) ** 2 + (high2 - p2) ** 2)
    upper = diff + np.sqrt((high1 - p1) ** 2 + (p2 - low2) ** 2)
    return float(max(-1.0, lower)), float(min(1.0, upper))


def clean_data(
    data_path: Path | str = DATA_PATH,
    *,
    check_expected: bool = True,
) -> tuple[pd.DataFrame, dict[str, int]]:
    """Load, validate and clean the supplied CSV.

    Structural checks always run. Exact row counts and headline totals are
    checked only when ``check_expected`` is true, so a new extract can be
    analysed deliberately with ``--no-expected-checks``.
    """
    raw = pd.read_csv(data_path, dtype=str)
    validate_input_schema(raw)
    for column in raw.columns:
        raw[column] = raw[column].str.strip()
    validate_input_schema(raw)

    stats_found: dict[str, int] = {
        "raw_rows": len(raw),
        "duplicate_rows": int(raw.duplicated().sum()),
        "work_mode_fixed": int(
            raw.work_mode.str.lower().str.replace("-", "_", regex=False).ne(raw.work_mode).sum()
        ),
        "missing_source": int(raw.source.isna().sum()),
    }

    df = raw.drop_duplicates().copy()
    df["work_mode"] = df.work_mode.str.lower().str.replace("-", "_", regex=False)
    df["source"] = df.source.fillna("unknown")
    try:
        df["applied_on"] = pd.to_datetime(df.applied_on, format="%Y-%m-%d", errors="raise")
        stipend = pd.to_numeric(df.stipend_inr_month, errors="raise")
        steps = pd.to_numeric(df.steps_done, errors="raise")
        df["days_to_first_reply"] = pd.to_numeric(df.days_to_first_reply, errors="raise")
    except (TypeError, ValueError) as exc:
        raise DataContractError(f"could not parse a date or numeric column: {exc}") from exc
    if not stipend.mod(1).eq(0).all() or not steps.mod(1).eq(0).all():
        raise DataContractError("stipend and steps must be whole numbers")
    df["stipend_inr_month"] = stipend.astype(int)
    df["steps_done"] = steps.astype(int)
    for column in ("shortlisted", "interviewed", "hired"):
        df[column] = df[column].str.lower()

    df["shortlisted_i"] = df.shortlisted.eq("yes").astype(int)
    df["interviewed_i"] = df.interviewed.eq("yes").astype(int)
    df["hired_i"] = df.hired.eq("yes").astype(int)
    df["completed_all_steps"] = df.steps_done.eq(4)
    df["paid"] = df.stipend_inr_month.gt(0)
    df["replied"] = df.days_to_first_reply.notna()

    stats_found["rows"] = len(df)
    stats_found["missing_reply"] = int((~df.replied).sum())
    stats_found["unpaid"] = int((~df.paid).sum())
    stats_found["paid"] = int(df.paid.sum())

    # Domain and consistency checks always run.
    if not df.application_id.is_unique:
        duplicate_ids = sorted(df.loc[df.application_id.duplicated(), "application_id"].unique())
        raise DataContractError(
            "application_id is not unique after removing exact duplicates: "
            + ", ".join(duplicate_ids[:5])
        )
    assert set(df.role_category) <= set(ROLE_ORDER), "unexpected role_category"
    assert set(df.work_mode) <= {"remote", "hybrid", "on_site"}, "unexpected work_mode"
    assert set(df.source) <= set(SOURCE_ORDER) | {"unknown"}, "unexpected source"
    for column in ("shortlisted", "interviewed", "hired"):
        assert set(df[column]) <= YES_NO, f"unexpected value in {column}"
    assert df.steps_done.between(0, 4).all(), "steps_done outside 0-4"
    assert df.stipend_inr_month.ge(0).all(), "negative stipend"
    assert df.days_to_first_reply.dropna().ge(1).all(), "reply days below 1"
    assert df.days_to_first_reply.dropna().le(32).all(), "reply days beyond chart range"
    assert (df.hired_i <= df.interviewed_i).all(), "hired without interview"
    assert (df.interviewed_i <= df.shortlisted_i).all(), "interviewed without shortlist"
    assert (df.loc[~df.replied, "shortlisted_i"] == 0).all(), "shortlisted row with no reply date"

    if check_expected:
        # Supplied-file contract and headline checks used by the memo and README.
        assert len(df) == 1200, f"expected 1,200 rows after dedup, got {len(df)}"
        assert df.applied_on.min() == pd.Timestamp("2026-07-01")
        assert df.applied_on.max() == pd.Timestamp("2026-09-30")
        assert int(df.shortlisted_i.sum()) == 269
        assert int(df.interviewed_i.sum()) == 175
        assert int(df.hired_i.sum()) == 64
        assert int(df.completed_all_steps.sum()) == 403
        assert stats_found["raw_rows"] == 1206
        assert stats_found["duplicate_rows"] == 6
        assert stats_found["work_mode_fixed"] == 9
        assert stats_found["missing_source"] == 15
        assert stats_found["missing_reply"] == 234
        assert stats_found["unpaid"] == 466
        assert stats_found["paid"] == 734

    return df, stats_found


def build_data_quality_report(
    df: pd.DataFrame,
    stats_found: dict[str, int],
    data_path: Path | str,
) -> dict[str, object]:
    """Machine-readable checks across the main data-quality dimensions."""
    checks: list[dict[str, object]] = []

    def add(
        dimension: str,
        check: str,
        status: str,
        observed: str,
        expectation: str,
        detail: str = "",
    ) -> None:
        assert status in {"pass", "warn", "fail", "not_assessed"}
        checks.append(
            {
                "dimension": dimension,
                "check": check,
                "status": status,
                "observed": observed,
                "expectation": expectation,
                "detail": detail,
            }
        )

    core_fields = [
        column for column in REQUIRED_COLUMNS if column not in {"source", "days_to_first_reply"}
    ]
    core_nulls = int(df[core_fields].isna().sum().sum())
    add(
        "completeness",
        "core_fields_present",
        "pass" if core_nulls == 0 else "fail",
        f"{core_nulls} null(s) across {len(core_fields)} fields",
        "0 nulls",
        "source and reply date are assessed separately.",
    )
    add(
        "completeness",
        "source_missing",
        "warn" if stats_found["missing_source"] else "pass",
        f"{stats_found['missing_source']} of {len(df):,} "
        f"({100 * stats_found['missing_source'] / len(df):.2f}%)",
        "0 missing",
        "Labelled unknown and excluded from source comparisons; none were hired.",
    )
    add(
        "completeness",
        "reply_date_missing",
        "warn" if stats_found["missing_reply"] else "pass",
        f"{stats_found['missing_reply']} of {len(df):,} "
        f"({100 * stats_found['missing_reply'] / len(df):.2f}%)",
        "Structural missingness is allowed",
        "Treated as no reply by 30 September 2026; not imputed.",
    )
    add(
        "uniqueness",
        "application_id_unique",
        "pass" if df.application_id.is_unique else "fail",
        f"{df.application_id.nunique():,} unique IDs",
        "One row per application_id",
    )
    add(
        "uniqueness",
        "exact_duplicates_removed",
        "pass" if stats_found["duplicate_rows"] == 6 else "warn",
        f"{stats_found['duplicate_rows']} exact duplicate row(s)",
        "6 in the supplied file",
        f"Dropped before analysis; {stats_found['raw_rows']:,} -> {len(df):,} rows.",
    )
    add(
        "validity",
        "categorical_domains",
        "pass",
        f"{df.role_category.nunique()} roles, {df.work_mode.nunique()} work modes, "
        "5 ranked sources + unknown",
        "Allowed categories only",
    )
    add(
        "validity",
        "numeric_ranges",
        "pass",
        "steps 0-4; stipend >= 0; reply days 1-32 when present",
        "Ranges match the data dictionary",
    )
    add(
        "validity",
        "application_dates",
        "pass"
        if df.applied_on.min() == pd.Timestamp("2026-07-01")
        and df.applied_on.max() == pd.Timestamp("2026-09-30")
        else "warn",
        f"{df.applied_on.min():%Y-%m-%d} to {df.applied_on.max():%Y-%m-%d}",
        "2026-07-01 to 2026-09-30",
    )
    add(
        "consistency",
        "funnel_order",
        "pass",
        f"{int(df.shortlisted_i.sum())} shortlisted, {int(df.interviewed_i.sum())} interviewed, "
        f"{int(df.hired_i.sum())} hired",
        "hired subset of interviewed subset of shortlisted",
    )
    add(
        "consistency",
        "no_reply_rows_not_shortlisted",
        "pass",
        f"{int((~df.replied).sum())} rows without a reply date",
        "No shortlisted row has a blank reply date",
    )
    add(
        "timeliness",
        "snapshot_coverage",
        "pass" if df.applied_on.max() == pd.Timestamp("2026-09-30") else "warn",
        f"snapshot ends {df.applied_on.max():%Y-%m-%d}",
        "30 September 2026 snapshot",
    )
    add(
        "distribution",
        "paid_unpaid_split",
        "pass" if stats_found["paid"] == 734 and stats_found["unpaid"] == 466 else "warn",
        f"{stats_found['paid']} paid, {stats_found['unpaid']} unpaid",
        "734 paid, 466 unpaid in the supplied file",
    )
    add(
        "distribution",
        "role_coverage",
        "pass" if df.role_category.nunique() == len(ROLE_ORDER) else "warn",
        f"{df.role_category.nunique()} of {len(ROLE_ORDER)} roles present",
        "All six role categories present",
    )
    add(
        "accuracy",
        "source_of_truth_reconciliation",
        "not_assessed",
        "No independent source",
        "Reconcile against the source system",
        "Not possible with the supplied synthetic extract.",
    )

    summary = {
        status: sum(1 for check in checks if check["status"] == status)
        for status in ("pass", "warn", "fail", "not_assessed")
    }
    return {
        "dataset": Path(data_path).name,
        "rows_raw": stats_found["raw_rows"],
        "rows_clean": len(df),
        "checks": checks,
        "summary": summary,
    }


def question_1(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Hires per 100 applications by source, overall and within role."""
    source = df.groupby("source", as_index=False).agg(
        applications=("application_id", "size"), hires=("hired_i", "sum")
    )
    source["hires_per_100"] = 100 * source.hires / source.applications
    source = add_wilson(source, "hires", "applications")

    role_rate = df.pivot_table(
        index="role_category", columns="source", values="hired_i", aggfunc="mean"
    )
    role_weights = df.role_category.value_counts(normalize=True)

    standardised = []
    for name in source.source:
        rates = role_rate[name].dropna()
        weights = role_weights.reindex(rates.index)
        standardised.append(100 * (rates * weights).sum() / weights.sum())
    source["role_standardised_per_100"] = standardised
    source["analysis_group"] = np.where(
        source.source.eq("unknown"), "excluded_missing_source", "ranked"
    )
    source = source.sort_values("hires_per_100", ascending=False).reset_index(drop=True)

    role_long = df.groupby(["role_category", "source"], as_index=False).agg(
        applications=("application_id", "size"), hires=("hired_i", "sum")
    )
    role_long = role_long[role_long.source.ne("unknown")]
    role_long["hires_per_100"] = 100 * role_long.hires / role_long.applications
    role_long = add_wilson(role_long, "hires", "applications")
    role_long["role_category"] = pd.Categorical(
        role_long.role_category, categories=ROLE_ORDER, ordered=True
    )
    role_long["source"] = pd.Categorical(role_long.source, categories=SOURCE_ORDER, ordered=True)
    role_long = role_long.sort_values(["role_category", "source"]).reset_index(drop=True)

    counts = source.set_index("source")
    referral_hires = int(counts.loc["referral", "hires"])
    referral_n = int(counts.loc["referral", "applications"])
    tests = []
    for name in SOURCE_ORDER:
        if name == "referral":
            continue
        other_hires = int(counts.loc[name, "hires"])
        other_n = int(counts.loc[name, "applications"])
        table = [
            [referral_hires, referral_n - referral_hires],
            [other_hires, other_n - other_hires],
        ]
        _, p_value = stats.fisher_exact(table)
        tests.append(
            {
                "comparison": f"referral vs {name}",
                "referral_hires": referral_hires,
                "referral_n": referral_n,
                "other_hires": other_hires,
                "other_n": other_n,
                "p_value": p_value,
            }
        )
    tests_df = pd.DataFrame(tests)
    tests_df["p_adjusted"] = stats.false_discovery_control(tests_df.p_value.to_numpy())

    log("Q1. Hires per 100 applications by source")
    for _, row in source.iterrows():
        log(
            f"  {row.source:<8} {row.applications:>4} apps  {row.hires:>3} hires  "
            f"{row.hires_per_100:5.1f} per 100  (95% CI {row.ci_low:4.1f}-{row.ci_high:4.1f})  "
            f"role-standardised {row.role_standardised_per_100:5.1f}"
        )
    adjusted_text = "; ".join(
        f"{row.comparison.replace('referral vs ', '')} p={row.p_value:.3g} "
        f"(BH {row.p_adjusted:.3g})"
        for _, row in tests_df.iterrows()
    )
    log(f"  Fisher exact vs referral: {adjusted_text}")
    log("  Role leaders:")
    for role in ROLE_ORDER:
        subset = role_long[role_long.role_category.eq(role)]
        best = subset.loc[subset.hires_per_100.idxmax()]
        log(f"    {role:<10} {best.source:<8} {best.hires_per_100:5.1f} per 100")
    log()

    return source, role_long, tests_df


def question_2(
    df: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Shortlist rate for applicants who complete all 4 steps vs those who do not."""
    by_step = df.groupby("steps_done", as_index=False).agg(
        applications=("application_id", "size"), shortlisted=("shortlisted_i", "sum")
    )
    by_step["shortlist_rate_pct"] = 100 * by_step.shortlisted / by_step.applications
    by_step = add_wilson(by_step, "shortlisted", "applications")

    groups = []
    for label, mask in (
        ("all 4 steps", df.completed_all_steps),
        ("0-3 steps", ~df.completed_all_steps),
    ):
        subset = df[mask]
        groups.append(
            {
                "group": label,
                "applications": len(subset),
                "shortlisted": int(subset.shortlisted_i.sum()),
                "shortlist_rate_pct": 100 * subset.shortlisted_i.mean(),
            }
        )
    comparison = add_wilson(pd.DataFrame(groups), "shortlisted", "applications")

    all4 = comparison.iloc[0]
    early = comparison.iloc[1]
    diff_pp = all4.shortlist_rate_pct - early.shortlist_rate_pct
    risk_ratio = all4.shortlist_rate_pct / early.shortlist_rate_pct
    ci_low, ci_high = newcombe_diff(
        int(all4.shortlisted),
        int(all4.applications),
        int(early.shortlisted),
        int(early.applications),
    )
    chi2, p_value, _, _ = stats.chi2_contingency(
        pd.crosstab(df.completed_all_steps, df.shortlisted_i)
    )
    tests = pd.DataFrame(
        [
            {
                "difference_pp": diff_pp,
                "difference_ci_low_pp": 100 * ci_low,
                "difference_ci_high_pp": 100 * ci_high,
                "risk_ratio": risk_ratio,
                "chi2": chi2,
                "p_value": p_value,
                "n_all4": int(all4.applications),
                "n_0_3": int(early.applications),
            }
        ]
    )

    rows = []
    role_p_values = []
    for role in ROLE_ORDER:
        subset = df[df.role_category.eq(role)]
        a = subset[subset.completed_all_steps]
        b = subset[~subset.completed_all_steps]
        table = [
            [int(a.shortlisted_i.sum()), int(len(a) - a.shortlisted_i.sum())],
            [int(b.shortlisted_i.sum()), int(len(b) - b.shortlisted_i.sum())],
        ]
        _, role_p = stats.fisher_exact(table)
        role_low, role_high = newcombe_diff(
            int(a.shortlisted_i.sum()),
            len(a),
            int(b.shortlisted_i.sum()),
            len(b),
        )
        role_p_values.append(role_p)
        rows.append(
            {
                "role_category": role,
                "applications": len(subset),
                "n_all4": len(a),
                "shortlist_pct_all4": 100 * a.shortlisted_i.mean(),
                "n_0_3": len(b),
                "shortlist_pct_0_3": 100 * b.shortlisted_i.mean(),
                "diff_pp": 100 * (a.shortlisted_i.mean() - b.shortlisted_i.mean()),
                "diff_ci_low_pp": 100 * role_low,
                "diff_ci_high_pp": 100 * role_high,
                "risk_ratio": a.shortlisted_i.mean() / b.shortlisted_i.mean(),
                "p_value": role_p,
            }
        )
    by_role = pd.DataFrame(rows)
    by_role["p_adjusted"] = stats.false_discovery_control(role_p_values)

    log("Q2. Shortlisting by application-step completion")
    for _, row in comparison.iterrows():
        log(
            f"  {row.group:<12} {row.applications:>4} apps  {row.shortlisted:>3} shortlisted  "
            f"{row.shortlist_rate_pct:5.1f}%  (95% CI {row.ci_low:4.1f}-{row.ci_high:4.1f})"
        )
    log(
        f"  Difference: +{diff_pp:.1f} pp (95% CI {100 * ci_low:.1f}-{100 * ci_high:.1f}); "
        f"risk ratio {risk_ratio:.2f}; chi-square p {p_value:.2g}"
    )
    log(
        "  By role gap: "
        + ", ".join(f"{r.role_category} +{r.diff_pp:.1f} pp" for r in by_role.itertuples())
        + f" (max BH p {by_role.p_adjusted.max():.2g})"
    )
    log()

    return by_step, comparison, tests, by_role


def reply_stats(group: pd.DataFrame) -> dict[str, object]:
    replied = group.days_to_first_reply.dropna()
    return {
        "applications": len(group),
        "replied": len(replied),
        "never_replied": int((~group.replied).sum()),
        "never_replied_pct": 100 * (1 - len(replied) / len(group)),
        "median_days": replied.median(),
        "mean_days": replied.mean(),
        "p75_days": replied.quantile(0.75),
        "p90_days": replied.quantile(0.90),
        "max_days": replied.max(),
    }


def question_3(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Reply speed and never-replied share for paid vs unpaid roles."""
    rows = [
        {"group": label, **reply_stats(subset)}
        for label, subset in (("paid", df[df.paid]), ("unpaid", df[~df.paid]))
    ]
    summary = add_wilson(pd.DataFrame(rows), "never_replied", "applications")

    paid_days = df[df.paid].days_to_first_reply.dropna()
    unpaid_days = df[~df.paid].days_to_first_reply.dropna()
    mann_whitney = stats.mannwhitneyu(paid_days, unpaid_days, alternative="two-sided")
    never_chi2, never_p, _, _ = stats.chi2_contingency(pd.crosstab(df.paid, df.replied))
    never_low, never_high = newcombe_diff(
        int(summary.loc[1, "never_replied"]),
        int(summary.loc[1, "applications"]),
        int(summary.loc[0, "never_replied"]),
        int(summary.loc[0, "applications"]),
    )
    tests = pd.DataFrame(
        [
            {
                "median_diff_days": summary.loc[1, "median_days"] - summary.loc[0, "median_days"],
                "mean_diff_days": summary.loc[1, "mean_days"] - summary.loc[0, "mean_days"],
                "never_reply_diff_pp": summary.loc[1, "never_replied_pct"]
                - summary.loc[0, "never_replied_pct"],
                "never_reply_diff_ci_low_pp": 100 * never_low,
                "never_reply_diff_ci_high_pp": 100 * never_high,
                "mannwhitney_u": mann_whitney.statistic,
                "mannwhitney_p": mann_whitney.pvalue,
                "never_reply_chi2": never_chi2,
                "never_reply_p": never_p,
            }
        ]
    )

    month = df.assign(month=df.applied_on.dt.to_period("M").astype(str))
    cutoff = df.applied_on.max() - pd.Timedelta(days=21)
    scopes = [(f"month {name}", subset) for name, subset in month.groupby("month")]
    scopes.append(("matured >=21 days", df[df.applied_on <= cutoff]))
    robustness = []
    for scope, subset in scopes:
        for label, group in (("paid", subset[subset.paid]), ("unpaid", subset[~subset.paid])):
            row = reply_stats(group)
            robustness.append(
                {
                    "scope": scope,
                    "group": label,
                    "applications": row["applications"],
                    "never_replied": row["never_replied"],
                    "never_replied_pct": row["never_replied_pct"],
                    "median_days": row["median_days"],
                    "mean_days": row["mean_days"],
                }
            )
    robustness_df = add_wilson(pd.DataFrame(robustness), "never_replied", "applications")

    log("Q3. Reply speed, paid vs unpaid roles")
    for _, row in summary.iterrows():
        log(
            f"  {row.group:<6} {row.applications:>4} apps  {row.replied:>4} replied  "
            f"never {row.never_replied:>3} ({row.never_replied_pct:4.1f}%, "
            f"95% CI {row.ci_low:4.1f}-{row.ci_high:4.1f}%)  "
            f"median {row.median_days:4.1f}d  mean {row.mean_days:4.1f}d  p90 {row.p90_days:4.1f}d"
        )
    log(
        f"  Median gap {tests.loc[0, 'median_diff_days']:.1f}d; never-reply gap "
        f"{tests.loc[0, 'never_reply_diff_pp']:.1f} pp "
        f"(95% CI {tests.loc[0, 'never_reply_diff_ci_low_pp']:.1f}-"
        f"{tests.loc[0, 'never_reply_diff_ci_high_pp']:.1f}); "
        f"Mann-Whitney p {mann_whitney.pvalue:.2g}"
    )
    log()

    return summary, tests, robustness_df


